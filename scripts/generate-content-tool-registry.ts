import { access, mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { format } from "prettier";

import {
  CONTENT_TOOL_SURFACES,
  type ContentToolManifest,
} from "../src/content-tools/types";

const root = process.cwd();
const toolsDirectory = path.join(root, "src/content-tools");
const generatedDirectory = path.join(toolsDirectory, "generated");
const checkOnly = process.argv.includes("--check");

interface ToolPackage {
  directory: string;
  manifest: ContentToolManifest;
}

async function fileExists(file: string): Promise<boolean> {
  try {
    await access(file);
    return true;
  } catch {
    return false;
  }
}

function validateManifest(
  directory: string,
  value: unknown,
): asserts value is ContentToolManifest {
  if (!value || typeof value !== "object") {
    throw new Error(`${directory}: manifest must export an object.`);
  }
  const manifest = value as Partial<ContentToolManifest>;
  if (!manifest.slug || !/^[A-Za-z][A-Za-z0-9]*$/.test(manifest.slug)) {
    throw new Error(
      `${directory}: slug must be a non-empty Payload block identifier.`,
    );
  }
  if (manifest.kind !== undefined && manifest.kind !== "tool") {
    throw new Error(`${directory}: unsupported content-tool kind.`);
  }
  if (
    manifest.width !== undefined &&
    manifest.width !== "prose" &&
    manifest.width !== "wide"
  ) {
    throw new Error(`${directory}: width must be "prose" or "wide".`);
  }
  for (const surface of manifest.surfaces ?? CONTENT_TOOL_SURFACES) {
    if (!CONTENT_TOOL_SURFACES.includes(surface)) {
      throw new Error(`${directory}: unsupported surface "${surface}".`);
    }
  }
}

async function discoverTools(): Promise<ToolPackage[]> {
  const entries = await readdir(toolsDirectory, { withFileTypes: true });
  const packages: ToolPackage[] = [];
  const slugs = new Set<string>();

  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    if (!entry.isDirectory() || entry.name === "generated") continue;
    const directory = path.join(toolsDirectory, entry.name);
    const required = ["manifest.ts", "block.server.ts", "renderer.client.tsx"];
    const missing = [];
    for (const file of required) {
      if (!(await fileExists(path.join(directory, file)))) missing.push(file);
    }
    if (missing.length > 0) {
      throw new Error(`${entry.name}: missing ${missing.join(", ")}.`);
    }

    const moduleURL = pathToFileURL(path.join(directory, "manifest.ts"));
    moduleURL.searchParams.set("generatedAt", String(Date.now()));
    const module = (await import(moduleURL.href)) as { default?: unknown };
    validateManifest(entry.name, module.default);
    if (slugs.has(module.default.slug)) {
      throw new Error(`Duplicate content-tool slug: ${module.default.slug}.`);
    }
    slugs.add(module.default.slug);
    packages.push({ directory: entry.name, manifest: module.default });
  }

  return packages;
}

function serverRegistry(packages: ToolPackage[]): string {
  const imports = packages
    .map(
      (tool, index) =>
        `import block${index} from "../${tool.directory}/block.server";\nimport manifest${index} from "../${tool.directory}/manifest";`,
    )
    .join("\n");
  const entries = packages
    .map(
      (_tool, index) =>
        `  { block: block${index}, manifest: resolveContentToolManifest(manifest${index}) },`,
    )
    .join("\n");

  return `// Generated by scripts/generate-content-tool-registry.ts. Do not edit.\n\nimport type { Block } from "payload";\n\nimport { resolveContentToolManifest, type ContentToolSurface, type ResolvedContentToolManifest } from "../types";\n${imports ? `\n${imports}\n` : ""}\ninterface ContentToolDefinition {\n  block: Block;\n  manifest: ResolvedContentToolManifest;\n}\n\nexport const contentToolDefinitions: readonly ContentToolDefinition[] = [\n${entries}\n];\n\nexport function getContentToolBlocks(surface: ContentToolSurface): Block[] {\n  return contentToolDefinitions\n    .filter(({ manifest }) => manifest.surfaces.includes(surface))\n    .map(({ block }) => block);\n}\n`;
}

function clientRegistry(packages: ToolPackage[]): string {
  const imports = packages
    .map(
      (tool, index) =>
        `import manifest${index} from "../${tool.directory}/manifest";\nimport render${index} from "../${tool.directory}/renderer.client";`,
    )
    .join("\n");
  const entries = packages
    .map(
      (_tool, index) =>
        `  [manifest${index}.slug]: {\n    render: render${index},\n    width: resolveContentToolManifest(manifest${index}).width,\n  },`,
    )
    .join("\n");

  return `// Generated by scripts/generate-content-tool-registry.ts. Do not edit.\n\n"use client";\n\nimport { resolveContentToolManifest, type ContentToolRenderer, type ContentToolWidth } from "../types";\n${imports ? `\n${imports}\n` : ""}\ninterface ContentToolRendererDefinition {\n  render: ContentToolRenderer;\n  width: ContentToolWidth;\n}\n\nexport const contentToolRenderers: Readonly<Record<string, ContentToolRendererDefinition>> = {\n${entries}\n};\n`;
}

async function syncFile(file: string, content: string): Promise<void> {
  content = await format(content, { parser: "typescript" });
  const current = await readFile(file, "utf8").catch(() => "");
  if (current === content) return;
  if (checkOnly) {
    throw new Error(
      `${path.relative(root, file)} is stale. Run bun run content-tools:generate.`,
    );
  }
  await writeFile(file, content);
}

const packages = await discoverTools();
await mkdir(generatedDirectory, { recursive: true });
await syncFile(
  path.join(generatedDirectory, "server.ts"),
  serverRegistry(packages),
);
await syncFile(
  path.join(generatedDirectory, "client.tsx"),
  clientRegistry(packages),
);

console.log(
  `${checkOnly ? "Checked" : "Generated"} ${packages.length} content tool${packages.length === 1 ? "" : "s"}.`,
);
